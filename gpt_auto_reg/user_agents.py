@dataclass(frozen=True, slots=True)
class UserAgentCatalog:
    entries: tuple[str, ...]

    def all(self) -> list[str]:
        return list(self.entries)

    def chromium(self) -> list[str]:
        return [entry for entry in self.entries if "Chrome/" in entry or "Edg/" in entry]

    def pick_random(self, chromium_only: bool = False) -> str:
        pool = self.chromium() if chromium_only else list(self.entries)
        return random.choice(pool)


DEFAULT_USER_AGENT_CATALOG = UserAgentCatalog(tuple(USER_AGENTS))
